/// **د یوه ولایت بلې مشهورې املا.**
///
/// دا اړینه ده ځکه چې د افغانستان څو ولایتونه دوه عامې لیکنې لري:
/// څوک «کندهار» لیکي، څوک «قندهار»؛ څوک «ارزګان»، څوک «اورزگان».
/// دلته یوازې یوه بڼه ساتل کېږي (هغه چې د رسمي ډیټاسیټ ده)، خو
/// لټون باید دواړه ومني — که نه، کارن به خپل ولایت ونه موند او
/// ګومان به يې کاوه چې لیسټ نیمګړی دی.
const Map<String, String> provinceAliases = {
  'کندهار': 'قندهار',
  'ارزگان': 'اورزگان',
  'ارزګان': 'اورزگان',
  'اروزګان': 'اورزگان',
  'اورزګان': 'اورزگان',
  'کندز': 'کندز',
  'قندوز': 'کندز',
  'کنړ': 'کنر',
  'وردګ': 'میدان وردگ',
  'وردگ': 'میدان وردگ',
  'میدان وردګ': 'میدان وردگ',
  'دایکندي': 'دایکندی',
  'سرپل': 'سر پل',
  'جوزجان': 'جوزجان',
  'سمنګان': 'سمنگان',
  'بغلان': 'بغلان',
  'لوګر': 'لوگر',
  'غزني': 'غزنی',
};

/// یو نوم رسمي بڼې ته اړوي — که مو ونه پېژانده، هماغه راګرځي.
String canonicalProvince(String name) {
  final n = name.trim();
  if (provinceAliases.containsKey(n)) return provinceAliases[n]!;
  return n;
}

/// د یوه ولایت ولسوالۍ. که ولایت ونه پېژندل شي، تشه لیسټ.
List<String> districtsOf(String? province) {
  if (province == null || province.isEmpty) return const [];
  final needle = canonicalProvince(province);
  for (final p in afghanistanProvinces) {
    if (p.name == needle) return p.districts;
  }
  return const [];
}

/// د ټایپ پر مهال وړاندیز — د نوم په هره برخه کې لټوي.
///
/// **ولې `contains` نه یوازې `startsWith`؟** ځکه چې کارن ښايي
/// «مرغاب» ولیکي او «بالا مرغاب» غواړي. که یوازې له سره پیل
/// لټوو، هغه به يې نه موند.
List<String> suggestFrom(List<String> pool, String query, {int limit = 8}) {
  final q = _normalize(query);
  if (q.isEmpty) return pool.take(limit).toList();

  // که کارن بله املا ولیکله، رسمي بڼه هم په لټون کې شامله شي.
  final alias = provinceAliases[query.trim()];

  final starts = <String>[];
  final contains = <String>[];
  for (final v in pool) {
    final n = _normalize(v);
    if (n.startsWith(q) || (alias != null && v == alias)) {
      starts.add(v);
    } else if (n.contains(q)) {
      contains.add(v);
    }
  }
  return [...starts, ...contains].take(limit).toList();
}

/// **د عربي/فارسي/پښتو د توري بڼې یو شان کوي.**
///
/// یو کارن «ي» (عربي یا) لیکي، بل «ی» (فارسي یا) — دواړه هماغه
/// غږ دی، خو Unicode يې دوه بېل کوډونه دي. پرته له دې نورمالولو،
/// «پکتيا» به «پکتیا» ونه موند او کارن به ګومان کاوه چې ولایت
/// په لیسټ کې نشته.
String _normalize(String s) => s
    .trim()
    .replaceAll('ي', 'ی')
    .replaceAll('ى', 'ی')
    .replaceAll('ك', 'ک')
    .replaceAll('ۀ', 'ه')
    .replaceAll('ة', 'ه')
    .replaceAll('ګ', 'گ')
    .replaceAll('‌', ' ');
